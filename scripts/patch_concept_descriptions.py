def patch(path: Path) -> int:
    text = path.read_text(encoding="utf-8")
    changes = 0

    # === 给 concept 加 description ===
    for nid, desc in CONCEPT_DEFINITIONS.items():
        # 模式：{"name": "...",\n                        "node_id": "pl_01",\n                        "search_query":
        # 在 "node_id" 行后插入 "description"
        pattern = re.compile(
            r'(\{\s*\n\s*"name":\s*"[^"]+",\s*\n\s*"node_id":\s*"'
            + re.escape(nid)
            + r'",\s*\n)(\s*"search_query")',
            re.MULTILINE,
        )
        replacement = r'\1                        "description": ' + q(desc) + r',\n\2'
        new_text, n = pattern.subn(replacement, text)
        if n > 0:
            text = new_text
            changes += n
            print(f"  + concept {nid}: description 已补全")
        else:
            if f'"node_id": "{nid}"' in text:
                print(f"  = concept {nid}: 已存在（可能已有 description）")
            else:
                print(f"  ! concept {nid}: 未找到")

    # === 增强 module description ===
    for mid, desc in MODULE_DEFINITIONS.items():
        # 用最直接的方式：找到 "id": "mid" 块，定位 description 行的原始内容，替换之。
        # 模式：\n\s*"id": "mid",\n\s*"name": "..."\n\s*"description": "原内容",
        pattern = re.compile(
            r'("id":\s*"' + re.escape(mid) + r'",\s*\n\s*"name":\s*"[^"]+",\s*\n\s*"description":\s*")[^"]*(",?)',
            re.MULTILINE,
        )
        replacement = r'\g<1>' + q(desc)[1:-1] + r'\g<2>'
        new_text, n = pattern.subn(replacement, text)
        if n > 0:
            text = new_text
            changes += n
            print(f"  + module {mid}: description 已增强")
        else:
            print(f"  ! module {mid}: 未找到（可能 id 不匹配）")

    path.write_text(text, encoding="utf-8")
    return changes


if __name__ == "__main__":
    p = Path("backend/kb/router.py")
    print(f"修改文件: {p}")
    n = patch(p)
    print(f"\n共修改 {n} 处")
